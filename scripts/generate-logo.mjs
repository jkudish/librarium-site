// Usage: node scripts/generate-logo.mjs <out-dir>, then copy LogoMark.astro to src/components,
// brand/*.svg to public/brand, and favicon.svg to public. Render PNGs with resvg (it supports masks).
// Final Librarium mark (B3 "Cut L"): a blocky L with 45-degree corner cuts and
// two receding layers (100% / 45% / 18% of one ink), separated by transparent
// gaps. Emits the brand SVG set and the Astro component body.
import { mkdirSync, writeFileSync } from 'node:fs';

const OUT = process.argv[2];
mkdirSync(`${OUT}/brand`, { recursive: true });

const SHAPE = [[0, 8], [8, 0], [20, 0], [20, 38], [50, 38], [50, 50], [42, 58], [0, 58]];
const D = 10;
const G = 2.6;
const OPACITY = [1, 0.45, 0.18];
const f = (n) => Math.round(n * 100) / 100;

const w = Math.max(...SHAPE.map((p) => p[0]));
const h = Math.max(...SHAPE.map((p) => p[1]));
const x0 = (100 - (w + 2 * D)) / 2;
const y0 = (100 - (h + 2 * D)) / 2 + 2 * D;
const layers = [0, 1, 2].map((k) => SHAPE.map(([x, y]) => [x0 + x + k * D, y0 + y - k * D]));
const pts = (p) => p.map(([x, y]) => `${f(x)},${f(y)}`).join(' ');

export function body(fill, id) {
  let defs = '';
  let out = '';
  for (let k = 2; k >= 1; k--) {
    defs += `<mask id="${id}-${k}" maskUnits="userSpaceOnUse" x="0" y="0" width="100" height="100"><rect width="100" height="100" fill="#fff"/>${layers
      .slice(0, k)
      .map((p) => `<polygon points="${pts(p)}" fill="#000" stroke="#000" stroke-width="${2 * G}"/>`)
      .join('')}</mask>`;
    out += `<polygon points="${pts(layers[k])}" fill="${fill}" fill-opacity="${OPACITY[k]}" mask="url(#${id}-${k})"/>`;
  }
  out += `<polygon points="${pts(layers[0])}" fill="${fill}"/>`;
  return { defs, out };
}

const svg = (fill, id, extra = '') => {
  const { defs, out } = body(fill, id);
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100"${extra}><defs>${defs}</defs>${out}</svg>\n`;
};
const icon = (bg, fill, id, rounded = true) => {
  const { defs, out } = body(fill, id);
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100"><defs>${defs}</defs><rect width="100" height="100"${rounded ? ' rx="22"' : ''} fill="${bg}"/><g transform="translate(18 18) scale(0.64)">${out}</g></svg>\n`;
};

writeFileSync(`${OUT}/brand/librarium-mark.svg`, svg('currentColor', 'lm'));
writeFileSync(`${OUT}/brand/librarium-mark-ink.svg`, svg('#0B0B0B', 'lm'));
writeFileSync(`${OUT}/brand/librarium-mark-paper.svg`, svg('#F9F8F5', 'lm'));
writeFileSync(`${OUT}/brand/librarium-mark-orange.svg`, svg('#C4501E', 'lm'));
writeFileSync(`${OUT}/brand/librarium-icon-orange.svg`, icon('#C4501E', '#FFFFFF', 'li'));
writeFileSync(`${OUT}/brand/librarium-icon-orange-square.svg`, icon('#C4501E', '#FFFFFF', 'li', false));
writeFileSync(`${OUT}/brand/librarium-icon-ink.svg`, icon('#0B0B0B', '#F9F8F5', 'li'));

// Browser chrome uses the rounded orange tile; operating systems round the
// full-bleed square app variant themselves.
writeFileSync(`${OUT}/favicon.svg`, icon('#C4501E', '#FFFFFF', 'li'));

// Astro component: inherits text colour; mask ids are namespaced by a prop so
// several instances can share a page.
const component = `---
// Librarium mark (B3 "Cut L"). Generated by the brand script; edit there.
interface Props { id: string; class?: string; title?: string }
const { id, class: className, title } = Astro.props;
---

<svg viewBox="0 0 100 100" data-brand="librarium" class={className} role={title ? "img" : undefined} aria-hidden={title ? undefined : "true"} aria-label={title}>
  <defs>
${[2, 1]
  .map(
    (k) => `    <mask id={\`\${id}-${k}\`} maskUnits="userSpaceOnUse" x="0" y="0" width="100" height="100"><rect width="100" height="100" fill="#fff" />${layers
      .slice(0, k)
      .map((p) => `<polygon points="${pts(p)}" fill="#000" stroke="#000" stroke-width="${2 * G}" />`)
      .join('')}</mask>`,
  )
  .join('\n')}
  </defs>
${[2, 1]
  .map((k) => `  <polygon points="${pts(layers[k])}" fill="currentColor" fill-opacity="${OPACITY[k]}" mask={\`url(#\${id}-${k})\`} />`)
  .join('\n')}
  <polygon points="${pts(layers[0])}" fill="currentColor" />
</svg>
`;
writeFileSync(`${OUT}/LogoMark.astro`, component);
console.log('ok');
